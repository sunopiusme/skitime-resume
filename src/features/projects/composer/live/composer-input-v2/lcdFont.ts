/* Глиф как массив рядов, где ряд — массив из 5 бит (0|1).
   Преобразуем один раз при загрузке модуля, чтобы в hot-path
   рендера не парсить строки. */
export type Glyph = number[][];

const GLYPHS: Record<string, Glyph> = Object.fromEntries(
  Object.entries(RAW).map(([ch, rows]) => [
    ch,
    rows.map((row) => Array.from(row, (bit) => (bit === "1" ? 1 : 0))),
  ]),
);

const SPACE = GLYPHS[" "]!;

/** Возвращает глиф для символа; неизвестные → пробел. */
export function getGlyph(ch: string): Glyph {
  return GLYPHS[ch] ?? SPACE;
}
